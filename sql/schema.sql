DROP TABLE IF EXISTS curated_spotify_tracks;

CREATE TABLE curated_spotify_tracks (
    source_row_id BIGINT,
    track_id VARCHAR PRIMARY KEY,
    artists VARCHAR,
    album_name VARCHAR,
    track_name VARCHAR,
    popularity BIGINT,
    duration_ms BIGINT,
    explicit BOOLEAN,
    danceability FLOAT,
    energy FLOAT,
    key BIGINT,
    loudness FLOAT,
    mode BIGINT,
    speechiness FLOAT,
    acousticness FLOAT,
    instrumentalness FLOAT,
    liveness FLOAT,
    valence FLOAT,
    tempo FLOAT,
    time_signature BIGINT,
    track_genre VARCHAR,
    pipeline_run_id VARCHAR,
    source_file VARCHAR,
    source_checksum VARCHAR,
    _etl_loaded_at VARCHAR,
    _ingest_mode VARCHAR,
    _staged_at VARCHAR,
    _staging_row_id BIGINT,
    popularity_tier VARCHAR,
    scaled_danceability FLOAT,
    scaled_energy FLOAT,
    scaled_valence FLOAT,
    scaled_acousticness FLOAT,
    scaled_liveness FLOAT,
    scaled_loudness FLOAT,
    scaled_tempo FLOAT,
    scaled_key FLOAT,
    scaled_mode FLOAT,
    scaled_time_signature FLOAT,
    scaled_instrumentalness FLOAT,
    scaled_speechiness FLOAT,
    split VARCHAR
);
