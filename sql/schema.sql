-- sql/schema.sql

DROP TABLE IF EXISTS curated_spotify_tracks;

CREATE TABLE curated_spotify_tracks (
    track_id VARCHAR(255) PRIMARY KEY,
    artists TEXT,
    album_name TEXT,
    track_name TEXT,
    popularity INTEGER,
    popularity_tier VARCHAR(10),
    duration_ms INTEGER,
    explicit BOOLEAN,
    danceability DOUBLE PRECISION,
    energy DOUBLE PRECISION,
    key INTEGER,
    loudness DOUBLE PRECISION,
    mode INTEGER,
    speechiness DOUBLE PRECISION,
    acousticness DOUBLE PRECISION,
    instrumentalness DOUBLE PRECISION,
    liveness DOUBLE PRECISION,
    valence DOUBLE PRECISION,
    tempo DOUBLE PRECISION,
    time_signature INTEGER,
    track_genre VARCHAR(255),
    scaled_danceability DOUBLE PRECISION,
    scaled_energy DOUBLE PRECISION,
    scaled_valence DOUBLE PRECISION,
    scaled_acousticness DOUBLE PRECISION,
    scaled_liveness DOUBLE PRECISION,
    scaled_loudness DOUBLE PRECISION,
    scaled_tempo DOUBLE PRECISION,
    scaled_key DOUBLE PRECISION,
    scaled_mode DOUBLE PRECISION,
    scaled_time_signature DOUBLE PRECISION,
    scaled_instrumentalness DOUBLE PRECISION,
    scaled_speechiness DOUBLE PRECISION,
    _staged_at TIMESTAMP,
    _staging_row_id INTEGER
);